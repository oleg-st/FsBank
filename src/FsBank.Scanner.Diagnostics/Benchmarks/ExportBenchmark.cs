using System.Diagnostics;
using System.Text.Json;
using FsBank.Scanner.Export;
using FsBank.Scanner.Scanning.Batch;

namespace FsBank.Scanner.Diagnostics.Benchmarks;

internal static class ExportBenchmark
{
    public static void Run(string sample, string output)
    {
        Directory.CreateDirectory(output);
        var measurements = new List<object>();
        foreach (bool debug in new[] { false, true })
        for (int iteration = 0; iteration < 3; iteration++)
        {
            using var export = new ScanExport(Path.Combine(output, $"{debug}-{iteration}"), debug);
            string capture = Path.Combine(export.WorkingRoot, "capture");
            // Copy outside the timed region; never modify the original captures.
            foreach (string file in Directory.EnumerateFiles(sample, "*", SearchOption.AllDirectories))
            {
                string target = Path.Combine(capture, Path.GetRelativePath(sample, file));
                Directory.CreateDirectory(Path.GetDirectoryName(target)!);
                File.Copy(file, target);
            }
            var timer = Stopwatch.StartNew();
            BatchRecognition.Run(capture, session => Path.Combine(session, "report.html"), _ => {}, CancellationToken.None);
            double batchSeconds = timer.Elapsed.TotalSeconds;
            if (iteration == 0)
            {
                using var expectedStream = File.OpenRead(Path.Combine(sample, "full.json"));
                using var actualStream = File.OpenRead(Path.Combine(capture, "full.json"));
                using var expectedFull = JsonDocument.Parse(expectedStream);
                using var actualFull = JsonDocument.Parse(actualStream);
                if (!JsonElement.DeepEquals(expectedFull.RootElement, actualFull.RootElement))
                    throw new InvalidOperationException("Batch merge changed diagnostic data. Use a baseline generated by the same report schema.");
            }
            timer.Restart();
            export.Complete(Console.WriteLine);
            double saveSeconds = timer.Elapsed.TotalSeconds;
            string destination = export.Destinations.Single();
            using var expected = JsonDocument.Parse(File.ReadAllBytes(Path.Combine(sample, "items.json")));
            using var actual = JsonDocument.Parse(File.ReadAllBytes(Path.Combine(destination, "items.json")));
            if (!JsonElement.DeepEquals(expected.RootElement, actual.RootElement))
                throw new InvalidOperationException("Export changed item data.");
            Checks.ScanExportCheck.CheckItemBrowser(destination);
            timer.Restart();
            export.Dispose();
            double cleanupSeconds = timer.Elapsed.TotalSeconds;
            measurements.Add(new { debug, iteration, items = actual.RootElement.GetArrayLength(), batchSeconds, saveSeconds, cleanupSeconds });
            Console.WriteLine($"Export benchmark: debug={debug}, batch={batchSeconds:F3}s, save={saveSeconds:F3}s, cleanup={cleanupSeconds:F3}s");
        }
        File.WriteAllText(Path.Combine(output, "timings.json"), JsonSerializer.Serialize(measurements, new JsonSerializerOptions { WriteIndented = true }));
    }
}
